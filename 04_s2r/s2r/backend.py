"""Contract for a future real Stretch backend. Protocol methods do not actuate."""
from typing import Protocol
from perception.observation import Observation
from vla.action_adapter import Action


class RealRobotBackend(Protocol):
    def get_observation(self, instruction: str = "") -> Observation: ...
    def apply_action(self, action: Action) -> None: ...
    def stop(self) -> None: ...
    def close(self) -> None: ...
